#!/usr/bin/env bash
# Writes the licenses of the libraries that ship in the app to THIRD-PARTY-NOTICES.txt.
# Re-run it and commit the result whenever dependencies are added or upgraded.
#
# - JavaScript: the dependencies of apps/desktop (transitively, `pnpm licenses list --prod`), plus the
#   devDependencies the build bundles into the page, listed in BUNDLED_DEV_PACKAGES. That list comes
#   from building with `vite build --sourcemap` and reading which node_modules packages its sources
#   name; add a package there when a new devDependency ends up in the bundle.
# - Rust: cargo-about (`cargo install cargo-about --locked --features cli`), configured by
#   apps/desktop/src-tauri/about.toml and formatted by about.hbs.
set -euo pipefail

cd "$(dirname "$0")/.."

OUT="THIRD-PARTY-NOTICES.txt"
DESKTOP="apps/desktop"

if ! cargo about --version >/dev/null 2>&1; then
  echo "Error: cargo-about is not installed. Run: cargo install cargo-about --locked --features cli" >&2
  exit 1
fi
if [ ! -d "$DESKTOP/node_modules" ]; then
  echo "Error: $DESKTOP/node_modules is missing. Run: pnpm -C $DESKTOP install" >&2
  exit 1
fi

# Made next to the output so the final mv is a rename: a copy that stops halfway would leave a broken file.
TMP=$(mktemp "${OUT}.XXXXXX")
PROD_JSON=$(mktemp "${OUT}.prod.XXXXXX")
ALL_JSON=$(mktemp "${OUT}.all.XXXXXX")
trap 'rm -f "$TMP" "$PROD_JSON" "$ALL_JSON"' EXIT

pnpm -C "$DESKTOP" licenses list --prod --json > "$PROD_JSON"
pnpm -C "$DESKTOP" licenses list --json > "$ALL_JSON"

{
  cat <<'HEADER'
THIRD-PARTY NOTICES

Flintkey bundles the open source libraries listed below. Each entry gives the
license, the packages it applies to, and the license text as shipped by the
package. Generated by scripts/generate-third-party-notices.sh; do not edit by hand.

################################################################################
# JavaScript packages (bundled into the web view)
################################################################################

HEADER

  PROD_JSON="$PROD_JSON" ALL_JSON="$ALL_JSON" node - <<'NODE'
const fs = require("fs");
const path = require("path");

const BUNDLED_DEV_PACKAGES = ["clsx", "svelte", "tailwindcss"];

const flatten = (file) => Object.values(JSON.parse(fs.readFileSync(file, "utf8"))).flat();

const packages = new Map();
const add = (entry) => {
  if (entry.versions.length !== 1) {
    // Which of them was bundled cannot be told from here.
    throw new Error(`${entry.name} has several versions: ${entry.versions.join(", ")}`);
  }
  packages.set(entry.name, { name: entry.name, version: entry.versions[0], dir: entry.paths[0] });
};
for (const entry of flatten(process.env.PROD_JSON)) add(entry);
const all = flatten(process.env.ALL_JSON);
for (const name of BUNDLED_DEV_PACKAGES) {
  const entry = all.find((e) => e.name === name);
  if (!entry) throw new Error(`${name} is not installed`);
  add(entry);
}

for (const pkg of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const manifest = JSON.parse(fs.readFileSync(path.join(pkg.dir, "package.json"), "utf8"));
  const repo = typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url;
  // LICENSE.spdx and the like are metadata, not license text.
  const files = fs
    .readdirSync(pkg.dir)
    .filter((f) => /^(LICEN[CS]E|COPYING|NOTICE)/i.test(f) && !/\.spdx$/i.test(f))
    .sort();
  if (files.length === 0) {
    throw new Error(`${pkg.name} ships no license file; add its license text by hand`);
  }
  console.log("=".repeat(80));
  console.log(`License: ${manifest.license}`);
  console.log("");
  console.log("Used by:");
  console.log(`  ${pkg.name} ${pkg.version}${repo ? ` (${repo})` : ""}`);
  console.log("");
  for (const f of files) {
    if (files.length > 1) console.log(`--- ${f} ---`);
    console.log(fs.readFileSync(path.join(pkg.dir, f), "utf8").replace(/\s+$/, ""));
    console.log("");
  }
}
NODE

  cat <<'HEADER'
################################################################################
# Rust crates (compiled into the binary)
################################################################################

HEADER

  # --fail: a crate whose license cannot be identified stops the script instead of being left out.
  cargo about generate --manifest-path "$DESKTOP/src-tauri/Cargo.toml" --locked --fail \
    "$DESKTOP/src-tauri/about.hbs"
} > "$TMP"

mv "$TMP" "$OUT"
echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
